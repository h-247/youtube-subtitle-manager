import { test, expect } from "@playwright/test";

test("login, ingestion progress, navigation, persisted editing and deletion", async ({ page, request }) => {
  const apiOrigins = new Set<string>();
  page.on("request", req => {
    const url = new URL(req.url());
    if (url.pathname.startsWith("/api/")) apiOrigins.add(url.origin);
  });
  const user = { email: `browser${Date.now()}@example.com`, password: "password123" };
  const response = await request.post("http://127.0.0.1:18000/api/auth/register", { data: user });
  expect(response.status()).toBe(201);
  await page.goto("/login");
  await page.getByRole("button", { name: "Email & Password" }).click();
  await page.getByPlaceholder("user@example.com").fill(user.email);
  await page.locator('input[type="password"]').fill("password123");
  await page.getByRole("button", { name: "Sign In", exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.goto("/dashboard/videos");
  await page.getByRole("button", { name: "Ingest Videos", exact: true }).click();
  await page.getByRole("textbox", { name: "New video tag" }).fill("Selected Tag");
  await page.getByRole("button", { name: "Add tag", exact: true }).click();
  await page.getByRole("textbox", {name: "Video URL", exact: true}).fill("https://youtu.be/abcdefghijk");
  await page.getByRole("button", { name: "Add video", exact: true }).click();
  await expect(page.getByText("Downloading subtitles...", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Channels", exact: true }).first().click();
  await expect(page).toHaveURL(/dashboard\/channels/);
  await expect(page.getByRole("link", { name: "Test Channel", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Videos", exact: true }).first().click();
  await expect(page).toHaveURL(/dashboard\/videos/);
  await expect(page.getByRole("button", {name: "Edit Tag", exact: true})).toHaveCount(0);
  await page.getByTitle("Edit status or ChatGPT link").click();
  await page.getByPlaceholder("https://chatgpt.com/c/...").fill("https://chatgpt.com/c/e2e");
  await page.getByRole("button", { name: "Save Changes" }).click();
  await page.reload();
  await expect(page.getByTitle("Open ChatGPT conversation")).toHaveAttribute("href", "https://chatgpt.com/c/e2e");
  await page.getByRole("button", { name: "Ingest Videos", exact: true }).click();
  await page.route("**/api/youtube/status", route => route.fulfill({json: {is_configured:true,is_connected:false,connect_url:"https://example.com/connect",pending_count:0,removed_count:0,failed_count:0,jobs:[]}}));
  await page.getByRole("button", { name: "YouTube playlist", exact: true }).click();
  await expect(page.getByRole("link", {name:"Connect YouTube",exact:true})).toBeVisible();
  await expect(page.getByRole("button", {name:"Add playlist",exact:true})).toBeDisabled();
  await page.unroute("**/api/youtube/status");
  await page.getByRole("button", {name:"Single video",exact:true}).click();
  await page.getByRole("button", {name:"YouTube playlist",exact:true}).click();
  await expect(page.getByRole("textbox", { name: "New video tag" })).toHaveCount(0);
  await page.getByRole("textbox", { name: "Playlist URL" }).fill("https://www.youtube.com/watch?v=abcdefghijk&list=PLfixture");
  await page.getByRole("button", {name: "Add playlist", exact: true}).click();
  await expect(page.getByText("Playlist fixture", {exact: true})).toBeVisible();
  await expect(page.getByRole("button", {name: "#English, AI & Learning", exact: true}).first()).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", {name: "#English, AI & Learning", exact: true}).first()).toBeVisible();
  const auth = await page.evaluate(() => localStorage.getItem("token"));
  const library = await request.get("http://127.0.0.1:18000/api/videos", {headers: {Authorization: `Bearer ${auth}`}});
  const records = (await library.json()).items;
  expect(records.find((v: any) => v.video_id === "abcdefghijk").tags).toEqual(["Selected Tag", "English, AI & Learning"]);
  expect(records.find((v: any) => v.video_id === "bcdefghijkl").tags).toEqual(["English, AI & Learning"]);
  page.on("dialog", dialog => dialog.accept());
  await page.getByTitle("Delete from library (leaves Google Drive file intact)").last().click();
  await page.reload();
  await expect(page.getByText("Browser fixture", { exact: true })).toHaveCount(0);
  expect([...apiOrigins]).toEqual(["http://127.0.0.1:13000"]);
});
